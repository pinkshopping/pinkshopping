-- Create one order header and all its line items atomically; stock is locked and decremented.
create or replace function public.place_order_with_variants(
  p_customer text,
  p_phone text,
  p_address text,
  p_items jsonb,
  p_payment_method text default 'scb_qr'
) returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_order_id bigint;
  v_first_product_id bigint;
  v_first_product_name text;
  v_first_quantity integer;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_variant public.product_variants%rowtype;
  v_product_id bigint;
  v_variant_id bigint;
  v_qty integer;
  v_price numeric(12,2);
  v_name text;
  v_label text;
begin
  if v_user is null then raise exception 'กรุณาเริ่มเซสชันลูกค้าก่อนสั่งซื้อ'; end if;
  if coalesce(trim(p_customer),'') = '' or coalesce(trim(p_phone),'') = '' or coalesce(trim(p_address),'') = '' then
    raise exception 'กรุณากรอกข้อมูลจัดส่งให้ครบ';
  end if;
  if p_payment_method not in ('scb_qr','cod') then raise exception 'วิธีชำระเงินไม่ถูกต้อง'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'ไม่มีสินค้าในคำสั่งซื้อ'; end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_variant_id := nullif(v_item->>'variant_id','')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 then raise exception 'จำนวนสินค้าไม่ถูกต้อง'; end if;

    select * into v_product from public.products where id = v_product_id and is_active = true for update;
    if not found then raise exception 'ไม่พบสินค้าหรือสินค้าปิดขายแล้ว (รหัส %) ', v_product_id; end if;
    v_name := v_product.name;

    if v_variant_id is not null then
      select * into v_variant from public.product_variants
        where id = v_variant_id and product_id = v_product_id and active = true for update;
      if not found then raise exception 'ไม่พบตัวเลือกสินค้านี้'; end if;
      if v_variant.stock < v_qty then raise exception 'สต็อกตัวเลือก % ไม่เพียงพอ', v_variant_id; end if;
      v_price := v_variant.price;
      v_label := concat_ws(' • ', nullif(v_variant.color,''), nullif(v_variant.size,''), nullif(v_variant.formula,''), nullif(v_variant.pack,''));
      update public.product_variants set stock = stock - v_qty where id = v_variant_id;
    else
      if v_product.stock < v_qty then raise exception 'สต็อกสินค้า % ไม่เพียงพอ', v_product.name; end if;
      v_price := v_product.price;
      v_label := null;
      update public.products set stock = stock - v_qty where id = v_product_id;
    end if;

    if v_first_product_id is null then
      v_first_product_id := v_product_id;
      v_first_product_name := v_product.name;
      v_first_quantity := v_qty;
    end if;
    v_total := v_total + v_price * v_qty;
  end loop;

  insert into public.orders (
    product_id, product_name, quantity, total_price,
    customer_name, customer_phone, customer_address, status,
    customer_uid, payment_method, payment_status
  ) values (
    v_first_product_id, v_first_product_name, v_first_quantity, v_total,
    trim(p_customer), trim(p_phone), trim(p_address), 'pending',
    v_user, p_payment_method, 'pending'
  ) returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_variant_id := nullif(v_item->>'variant_id','')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id = v_product_id;
    v_name := v_product.name;
    if v_variant_id is not null then
      select * into v_variant from public.product_variants where id = v_variant_id;
      v_price := v_variant.price;
      v_label := concat_ws(' • ', nullif(v_variant.color,''), nullif(v_variant.size,''), nullif(v_variant.formula,''), nullif(v_variant.pack,''));
    else
      v_price := v_product.price;
      v_label := null;
    end if;
    insert into public.order_items(order_id,product_id,variant_id,product_name,variant_label,quantity,unit_price)
    values(v_order_id,v_product_id,v_variant_id,v_name,v_label,v_qty,v_price);
  end loop;
  return v_order_id;
end;
$$;

-- A guest can submit a slip only for their own QR-paid order and only from their own storage folder.
create or replace function public.submit_payment_slip(p_order_id bigint, p_slip_path text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders%rowtype;
  v_payment_id bigint;
begin
  if auth.uid() is null then raise exception 'ไม่พบเซสชันลูกค้า'; end if;
  if split_part(p_slip_path,'/',1) <> auth.uid()::text
     or split_part(p_slip_path,'/',2) <> p_order_id::text then
    raise exception 'ตำแหน่งไฟล์สลิปไม่ถูกต้อง';
  end if;
  select * into v_order from public.orders
    where id = p_order_id and customer_uid = auth.uid() and payment_method = 'scb_qr'
    for update;
  if not found then raise exception 'ไม่พบคำสั่งซื้อของคุณหรือไม่ใช่คำสั่งซื้อแบบ QR'; end if;

  update public.orders set payment_slip_url = p_slip_path, payment_status = 'pending'
    where id = p_order_id;
  select id into v_payment_id from public.payments where order_id = p_order_id limit 1 for update;
  if v_payment_id is null then
    insert into public.payments(order_id,amount,payment_status,slip_url)
    values(p_order_id,v_order.total_price,'pending',p_slip_path);
  else
    update public.payments set amount = v_order.total_price, payment_status = 'pending', slip_url = p_slip_path
    where id = v_payment_id;
  end if;
end;
$$;

revoke all on function public.place_order_with_variants(text,text,text,jsonb,text) from public;
grant execute on function public.place_order_with_variants(text,text,text,jsonb,text) to authenticated;
revoke all on function public.submit_payment_slip(bigint,text) from public;
grant execute on function public.submit_payment_slip(bigint,text) to authenticated;


-- Safe owner-only cancellation with stock restoration from the order lines.
create or replace function public.cancel_order_and_restock(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders%rowtype;
  v_item record;
begin
  if (auth.jwt() ->> 'email') <> 'suriyonpraditthaen@gmail.com' then
    raise exception 'ไม่มีสิทธิ์ยกเลิกคำสั่งซื้อ';
  end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'ไม่พบคำสั่งซื้อ'; end if;
  if v_order.status in ('cancelled','completed') then raise exception 'คำสั่งซื้อนี้ไม่สามารถยกเลิกได้'; end if;
  for v_item in select product_id, variant_id, quantity from public.order_items where order_id = p_order_id loop
    if v_item.variant_id is not null then
      update public.product_variants set stock = stock + v_item.quantity where id = v_item.variant_id;
    else
      update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
    end if;
  end loop;
  update public.orders set status = 'cancelled' where id = p_order_id;
end;
$$;
revoke all on function public.cancel_order_and_restock(bigint) from public;
grant execute on function public.cancel_order_and_restock(bigint) to authenticated;

commit;
